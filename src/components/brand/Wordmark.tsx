import Image from 'next/image'
import type { CSSProperties } from 'react'
import { cn } from '@/lib/utils'
import colorTokens from '../../../tokens/src/color.json'

export type WordmarkVariant = 'light' | 'dark'
export type WordmarkSize = 'sm' | 'md' | 'lg'

export interface WordmarkProps {
  /**
   * The text to render. Default "BIOSCOPE".
   */
  text?: string
  /**
   * Array of color token names (e.g. 'letter-1', 'letter-2') for each letter.
   * Defaults to the 8 letter-* tokens in order.
   */
  letterColors?: readonly string[]
  /**
   * Wordmark colour. `light` is paper-coloured, for use on ink/dark surfaces;
   * `dark` is ink, for use on paper. The logo image itself never changes.
   * Default `dark`.
   */
  variant?: WordmarkVariant
  /** Lockup scale. Default `md`. */
  size?: WordmarkSize
  /**
   * Render a plain `<img>` instead of `next/image`, for the OG image runtime
   * where the image optimizer is unavailable. Colour styling switches from
   * `var(--…)` utilities to literal token values because satori cannot resolve
   * CSS custom properties. Default `false`.
   */
  raw?: boolean
  /**
   * Logo source. Defaults to the site logo path. The OG route passes a base64
   * data URI because satori rejects relative image URLs.
   */
  logoSrc?: string
  className?: string
}

interface SizeSpec {
  /** Square logo edge, in pixels. The source mark is 500×500. */
  logo: number
  fontSize: number
  gap: number
  textClass: string
  gapClass: string
}

const SIZES: Record<WordmarkSize, SizeSpec> = {
  sm: { logo: 28, fontSize: 20, gap: 8, textClass: 'text-xl', gapClass: 'gap-2' },
  md: { logo: 40, fontSize: 30, gap: 12, textClass: 'text-3xl', gapClass: 'gap-3' },
  lg: { logo: 56, fontSize: 48, gap: 16, textClass: 'text-5xl', gapClass: 'gap-4' },
}

interface ColorSpec {
  /** Tailwind utility for the browser path (resolves `var(--…)`). */
  className: string
  /** Literal token value for the satori/OG path. */
  raw: string
}

const VARIANT_COLORS: Record<WordmarkVariant, ColorSpec> = {
  dark: { className: 'text-[var(--ink)]', raw: colorTokens.ink.$value },
  light: { className: 'text-[var(--paper)]', raw: colorTokens.paper.$value },
}

/**
 * Default per-letter palette for "BIOSCOPE" (8 letters).
 * These map to the letter-1 through letter-8 tokens from the color system.
 */
const DEFAULT_LETTER_COLORS: readonly string[] = [
  'letter-1',
  'letter-2',
  'letter-3',
  'letter-4',
  'letter-5',
  'letter-6',
  'letter-7',
  'letter-8',
]

/**
 * Die-cut halo for the mark (spec §5.1: the primary mark is used "inside a
 * white die-cut treatment"). The source PNG is 500×500 RGBA with transparent
 * corners and an irregular silhouette — camera body, protruding lens, crank
 * handle, Bengali lettering, floral base — and no white border baked in. A
 * `box-shadow` ring would trace the square, so the halo is a `drop-shadow`
 * chain, which follows the alpha silhouette.
 *
 * Both layers need a non-zero blur. A 0px blur is not a valid ring: Chromium
 * computes `drop-shadow(0 0 0 Npx …)` to `none`, and a sub-pixel blur
 * ( `0.5px` ) is clipped to zero coverage at `sm` (28px) — measured: 0 halo
 * pixels. `1px` is the thinnest ring both the browser and the OG runtime draw.
 *
 * The browser path applies the `.die-cut-mark` utility from `globals.css`
 * (a plain rule, not a Tailwind arbitrary value — a bare multi-function filter
 * string is not generated by the compiler); the raw/OG path uses the literal
 * token values because satori cannot resolve CSS custom properties.
 */
const DIE_CUT_FILTER = {
  className: 'die-cut-mark',
  // Ink offset first, white halo last: a later drop-shadow paints over an
  // earlier one, so white-first lets the ink shadow cover the halo and leaves
  // a one-sided sliver at `sm` (21 lighter px, max +3) instead of a ring
  // (117 px, max +15). See the `.die-cut-mark` rule in globals.css.
  raw: `drop-shadow(1px 1px 0 ${colorTokens.ink.$value}) drop-shadow(0 0 1px ${colorTokens['die-cut'].$value})`,
} as const

/**
 * The bioscope lockup: the folk-art mark beside the Shrikhand wordmark.
 * One source of truth, two render paths — `next/image` for the app,
 * a plain `<img>` for the OG image runtime.
 */
export function Wordmark({
  text = 'BIOSCOPE',
  letterColors = DEFAULT_LETTER_COLORS,
  variant = 'dark',
  size = 'md',
  raw = false,
  logoSrc = '/images/bioscope-logo.png',
  className,
}: WordmarkProps) {
  const spec = SIZES[size]
  const color = VARIANT_COLORS[variant]

  const boxStyle: CSSProperties = {
    display: 'flex',
    alignItems: 'center',
    gap: spec.gap,
  }

  const wordmarkStyle: CSSProperties = {
    fontFamily: 'Shrikhand',
    fontSize: spec.fontSize,
    lineHeight: 1,
    color: color.raw,
  }

  // Build the colored letter spans
  const letters = text.split('')
  const coloredLetters = letters.map((letter, index) => {
    const tokenName = letterColors[index] || letterColors[letterColors.length - 1]
    const tokenValue = (colorTokens as Record<string, { $value: string }>)[tokenName]?.$value || color.raw

    if (raw) {
      return (
        <span
          key={index}
          style={{
            color: tokenValue,
            fontFamily: 'Shrikhand',
            fontSize: spec.fontSize,
            lineHeight: 1,
          }}
        >
          {letter}
        </span>
      )
    }

    return (
      <span
        key={index}
        className={cn('font-display leading-none tracking-tight', spec.textClass, `text-[var(--${tokenName})]`)}
      >
        {letter}
      </span>
    )
  })

  return (
    <span
      className={raw ? className : cn('flex items-center', spec.gapClass, className)}
      style={raw ? boxStyle : undefined}
    >
      {raw ? (
        // The OG image runtime has no image optimizer, so the raw path renders
        // a plain <img> (Ruling 2). The linter warning is expected here.
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={logoSrc}
          alt="BIOSCOPE"
          width={spec.logo}
          height={spec.logo}
          style={{
            width: spec.logo,
            height: spec.logo,
            objectFit: 'contain',
            filter: DIE_CUT_FILTER.raw,
          }}
        />
      ) : (
        <Image
          src={logoSrc}
          alt="BIOSCOPE"
          width={spec.logo}
          height={spec.logo}
          className={cn('shrink-0', DIE_CUT_FILTER.className)}
        />
      )}
      <span aria-hidden="true" className={raw ? undefined : 'flex'}>
        {coloredLetters}
      </span>
      {/* The split-letter wordmark above is hidden from assistive tech; this
          single text node carries the brand name. The OG render path omits it
          because satori ignores the `sr-only` utility and would draw it. */}
      {!raw && <span className="sr-only">{text}</span>}
    </span>
  )
}